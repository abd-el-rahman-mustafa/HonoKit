const dictionaries: Record<Language, Record<Key, string>> = { en, ar }

export function translate(language: Language, key: Key, values?: Record<string, string | number>): string {
  let text = dictionaries[language][key] ?? en[key] ?? key
  if (values) for (const [k, v] of Object.entries(values)) text = text.replaceAll(`{${k}}`, String(v))
  return text
}

