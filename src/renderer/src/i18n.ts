const countDictionaries: Record<Language, Record<CountKey, Forms>> = { en: enCounts, ar: arCounts }

/** A counted string in the form the language uses for `count`; `{count}` and other values filled in. */
export function translateCount(language: Language, key: CountKey, count: number, values?: Record<string, string | number>): string {
  const forms = countDictionaries[language][key] ?? enCounts[key]
  const rule = new Intl.PluralRules(language === 'ar' ? 'ar' : 'en').select(count)
  let text = forms[rule] ?? forms.other
  for (const [k, v] of Object.entries({ count, ...values })) text = text.replaceAll(`{${k}}`, String(v))
  return text
}

/** Whether a key sent by the engine (ApiError.key) is one of ours. */
export function hasKey(key: string): key is Key {
  return Object.prototype.hasOwnProperty.call(en, key)
}

export function errorKey(code: ErrorCode): Key {
  return `error.${code}` as Key
}

/** 1.2 MB, 350 KB — with Arabic-Indic digits in Arabic. */
export function formatBytes(language: Language, bytes: number): string {
  const units = language === 'ar' ? ['بايت', 'ك.ب', 'م.ب', 'ج.ب'] : ['B', 'KB', 'MB', 'GB']
  let n = bytes
  let u = 0
  while (n >= 1024 && u < units.length - 1) {
    n /= 1024
    u++
  }
  const value = new Intl.NumberFormat(language === 'ar' ? 'ar-EG' : 'en-US', { maximumFractionDigits: n < 10 && u > 0 ? 1 : 0 }).format(n)
  return `${value} ${units[u]}`
}
